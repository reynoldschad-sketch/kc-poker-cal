/**
 * Drag-and-drop target. Emits dist/ with everything Cloudflare needs in one folder,
 * including a single _worker.js so the /api routes still work without a git build.
 * Run: npm run build:dragdrop  →  drag dist/ onto Pages → Create → Direct Upload.
 */
import { readFileSync, writeFileSync, mkdirSync, cpSync } from "node:fs";

mkdirSync("dist", { recursive: true });
// reuse the normal build output
cpSync("public/index.html", "dist/index.html");
cpSync("public/calendar.ics", "dist/calendar.ics");
cpSync("public/_headers", "dist/_headers");

const matrix = readFileSync("functions/api/matrix.js", "utf8")
  .replace(/^export async function onRequestGet/m, "async function matrixGet")
  .replace(/^export async function onRequestPost/m, "async function matrixPost");
const calendar = readFileSync("functions/api/calendar.js", "utf8")
  .replace(/^import DATA.*$/m, "")
  .replace(/^export async function onRequestGet/m, "async function calendarGet");
const data = readFileSync("data/poker.json", "utf8");

writeFileSync("dist/_worker.js", `// generated by build-standalone.mjs -- do not edit
const DATA = ${data};
${matrix}
${calendar}
export default {
  async fetch(request, env) {
    const { pathname } = new URL(request.url);
    if (pathname === "/api/matrix") return request.method === "POST" ? matrixPost({ request, env }) : matrixGet({ env });
    if (pathname === "/api/calendar") return calendarGet({ request });
    return env.ASSETS.fetch(request);
  },
};
`);
console.log("built dist/ (index.html, calendar.ics, _headers, _worker.js) -- drag this folder onto Pages");
